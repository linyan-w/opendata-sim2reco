#!/usr/bin/env python
"""Concatenate surrogate ntuples (scripts/surrogate_to_ntuple.py --range slices) into one file, every tree in the given
order, read and written in steps so that the memory stays bounded; the `*_sz` counters are regenerated by the writer.
Usage: scripts/merge_ntuples.py OUT.root IN1.root IN2.root ... [--step 500000]"""
import argparse, pathlib, sys
sys.path.insert(0, str(pathlib.Path(__file__).resolve().parents[1]))
import awkward as ak, numpy as np, uproot
from sim2reco.io.writer import _counter_name, _type_of
ap = argparse.ArgumentParser(); ap.add_argument("out"); ap.add_argument("inputs", nargs="+"); ap.add_argument("--step", type=int, default=500000); a = ap.parse_args()
first = uproot.open(a.inputs[0]); trees = first.keys(cycle=False)
with uproot.recreate(a.out) as fo:
    for name in trees:
        names = [k for k in first[name].keys() if not k.endswith("_sz")]; jag = {k: first[name][k].typename.endswith("[]") for k in names}; made = False; n = 0
        for fn in a.inputs:
            t = uproot.open(fn)[name]; assert [k for k in t.keys() if not k.endswith("_sz")] == names, f"{fn}:{name}: branches differ from {a.inputs[0]}"
            for arr in t.iterate(names, step_size=a.step, library="ak"):
                data = {k: (ak.fill_none(arr[k], 0) if jag[k] else ak.to_numpy(arr[k])) for k in names}
                if not made: fo.mktree(name, {k: _type_of(v) for k, v in data.items()}, counter_name=_counter_name); made = True
                fo[name].extend(data); n += len(arr)
        print(f"{name}: {n:,} entries from {len(a.inputs)} files", flush=True)
print("written", a.out)
